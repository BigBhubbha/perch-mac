// The shelf: drop files on the island to keep them handy, AirDrop them, or drag them back out.
// Plus clipboard history, which skips anything a password manager marks as private.
import AppKit
import SwiftUI
import UniformTypeIdentifiers

struct ShelfItem: Codable, Identifiable, Equatable {
    var id = UUID()
    var path: String
    var added = Date()
    var url: URL { URL(fileURLWithPath: path) }
    var name: String { url.lastPathComponent }
    var exists: Bool { FileManager.default.fileExists(atPath: path) }
}

struct Clip: Codable, Identifiable, Equatable {
    var id = UUID()
    var text: String
    var copied = Date()
    var pinned = false
    var app: String?

    var kind: String {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if t.hasPrefix("http://") || t.hasPrefix("https://") { return "link" }
        if t.range(of: #"^#?[0-9a-fA-F]{6}$"#, options: .regularExpression) != nil { return "color" }
        if t.contains("{") || t.contains(";") && t.contains("\n") { return "code" }
        return "text"
    }
}

@MainActor
final class ShelfStore: ObservableObject {
    @Published var items: [ShelfItem] = []
    @Published var clips: [Clip] = []
    @Published var dropTargeted = false

    private let dir: URL
    private var poll: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var ownWrite = -1
    var onDrop: (Int) -> Void = { _ in }

    init() {
        dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("Perch", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        if let d = try? Data(contentsOf: dir.appendingPathComponent("shelf.json")), let v = try? JSONDecoder().decode([ShelfItem].self, from: d) {
            items = v.filter(\.exists)
        }
        if let d = try? Data(contentsOf: dir.appendingPathComponent("clips.json")), let v = try? JSONDecoder().decode([Clip].self, from: d) {
            clips = v
        }
    }

    // MARK: Files

    func add(_ urls: [URL]) {
        let fresh = urls.filter { u in !items.contains { $0.path == u.path } }.map { ShelfItem(path: $0.path) }
        guard !fresh.isEmpty else { return }
        items.insert(contentsOf: fresh, at: 0)
        if items.count > 24 { items.removeLast(items.count - 24) }
        saveShelf()
        onDrop(fresh.count)
    }

    func remove(_ i: ShelfItem) { items.removeAll { $0.id == i.id }; saveShelf() }
    func clearShelf() { items.removeAll(); saveShelf() }

    func airdrop(_ list: [ShelfItem]) {
        let urls = list.filter(\.exists).map(\.url)
        guard !urls.isEmpty, let s = NSSharingService(named: .sendViaAirDrop) else { return }
        if s.canPerform(withItems: urls) { s.perform(withItems: urls) }
    }

    func share(_ list: [ShelfItem], from view: NSView?) {
        let urls = list.filter(\.exists).map(\.url)
        guard !urls.isEmpty, let v = view else { return }
        NSSharingServicePicker(items: urls).show(relativeTo: v.bounds, of: v, preferredEdge: .minY)
    }

    func open(_ i: ShelfItem) { NSWorkspace.shared.open(i.url) }
    func reveal(_ i: ShelfItem) { NSWorkspace.shared.activateFileViewerSelecting([i.url]) }

    func icon(for i: ShelfItem) -> NSImage { NSWorkspace.shared.icon(forFile: i.path) }

    /// Accepts file drops from Finder and most apps.
    func accept(_ providers: [NSItemProvider]) -> Bool {
        var any = false
        for p in providers where p.hasItemConformingToTypeIdentifier(UTType.fileURL.identifier) {
            any = true
            _ = p.loadObject(ofClass: URL.self) { url, _ in
                guard let url else { return }
                DispatchQueue.main.async { MainActor.assumeIsolated { self.add([url]) } }
            }
        }
        return any
    }

    private func saveShelf() {
        if let d = try? JSONEncoder().encode(items) { try? d.write(to: dir.appendingPathComponent("shelf.json"), options: .atomic) }
    }

    // MARK: Clipboard

    func startClipboard() {
        guard poll == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        poll = Timer.scheduledTimer(withTimeInterval: 0.8, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkPasteboard() }
        }
        poll?.tolerance = 0.3
    }

    func stopClipboard() { poll?.invalidate(); poll = nil }

    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type", "com.nspasteboard.ConcealedType",
    ]

    private func checkPasteboard() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard pb.changeCount != ownWrite, Prefs.shared.clipboardOn else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes) else { return }
        guard let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, s.count < 20_000 else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        clips.removeAll { $0.text == s && !$0.pinned }
        if let i = clips.firstIndex(where: { $0.text == s }) { clips[i].copied = Date() } else {
            clips.insert(Clip(text: s, app: app), at: 0)
        }
        trim(); saveClips()
    }

    func copy(_ c: Clip) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(c.text, forType: .string)
        ownWrite = pb.changeCount
        if let i = clips.firstIndex(of: c) { var m = clips.remove(at: i); m.copied = Date(); clips.insert(m, at: 0) }
        saveClips()
    }

    func togglePin(_ c: Clip) {
        guard let i = clips.firstIndex(where: { $0.id == c.id }) else { return }
        clips[i].pinned.toggle(); saveClips()
    }

    func delete(_ c: Clip) { clips.removeAll { $0.id == c.id }; saveClips() }
    func clearClips() { clips.removeAll { !$0.pinned }; saveClips() }

    var sortedClips: [Clip] { clips.filter(\.pinned) + clips.filter { !$0.pinned } }

    private func trim() {
        let unpinned = clips.enumerated().filter { !$0.element.pinned }
        if unpinned.count > 40 {
            let drop = Set(unpinned.dropFirst(40).map(\.element.id))
            clips.removeAll { drop.contains($0.id) }
        }
    }

    private func saveClips() {
        if let d = try? JSONEncoder().encode(clips) { try? d.write(to: dir.appendingPathComponent("clips.json"), options: .atomic) }
    }

    func preview(items: [ShelfItem], clips: [Clip]) { self.items = items; self.clips = clips }
}
